#!/usr/bin/env bash
# A runtime handler declared in the configuration file runs pods, and stays
# declared across a containerd restart, a day-2 change and a second start.
#
# The handler is /inttest/fake-runtime, the payload's runc under another name,
# which logs each call: a pod that names its RuntimeClass and runs proves
# containerd loaded the handler, and its container's ID in that log proves the
# handler's binary ran it, not the default runc. A control plane reads
# spec.node.runtimeHandlers on every start and `stratum runtime apply` refuses
# handler flags there, so every change here is an edit of the file followed by
# `stratum runtime apply`.
. "$(dirname "$0")/harness.sh"

FAKE=/inttest/fake-runtime
LOG=/tmp/fake-runtime.log
DROPIN=$ROOT/config/containerd.d/stratum-runtime.toml
BB=$(/tools/mirror-images.sh --list | grep '/busybox:' | cut -d@ -f1)

config() {  # $1 the runtimeHandlers map, $2 the runtimeClasses list, as flow YAML
  mkdir -p /etc/stratum
  printf 'spec:\n  node:\n    runtimeHandlers: %s\n  runtimeClasses: %s\n' "$1" "$2" > /etc/stratum/config.yaml
}

node() { $K get nodes -o jsonpath='{.items[0].metadata.name}'; }
labels() { $K get node "$(node)" -o jsonpath='{.metadata.labels}'; }
has_label() { labels | grep -q "\"runtime.stratum.ciq.com/$1\":\"true\""; }
runtime_check() { "$STRATUM" runtime check 2>&1; }

# pod NAME [RUNTIMECLASS] runs a pod that sleeps, under that RuntimeClass if one
# is given.
pod() {
  local rc=""
  [[ -n ${2:-} ]] && rc="  runtimeClassName: $2"
  $K apply -f - >/dev/null <<EOF
apiVersion: v1
kind: Pod
metadata:
  name: $1
spec:
$rc
  terminationGracePeriodSeconds: 0
  containers:
  - name: c
    image: $BB
    command: ["sleep", "3600"]
EOF
}
running() { [[ $($K get pod "$1" -o jsonpath='{.status.phase}' 2>/dev/null) == Running ]]; }
container_id() { $K get pod "$1" -o jsonpath='{.status.containerStatuses[0].containerID}' | sed 's|^containerd://||'; }
ran_through_fake() { grep -q -- "$(container_id "$1")" "$LOG" 2>/dev/null; }

config "{fake: $FAKE}" "[fake]"
start_cluster
trap finish EXIT
ready() {
  wait_for "node registration" 120 sh -c "$K get nodes --no-headers | grep -q ."
  wait_for "node Ready" 300 sh -c "$K get nodes --no-headers | grep -vq NotReady"
  wait_for "default ServiceAccount" 60 sh -c "$K get sa default -n default"
}
ready

# --- the handler at start -------------------------------------------------------
dropin=$(cat "$DROPIN" 2>/dev/null || echo absent)
assert_contains "the drop-in carries the generated marker" "# generated by stratum" "$dropin"
assert_contains "the drop-in declares the fake handler" "containerd.runtimes.fake]" "$dropin"
assert_contains "…with the wrapper as its binary" "BinaryName = '$FAKE'" "$dropin"
if out=$(runtime_check); then pass "stratum runtime check passes"; else fail "stratum runtime check failed: $out"; fi

wait_for "the node's fake handler label" 120 has_label fake || fail "the node has no fake handler label: $(labels)"
rc_fake() { $K get runtimeclass fake -o jsonpath='{.handler} {.scheduling.nodeSelector}' 2>/dev/null; }
wait_for "the fake RuntimeClass" 180 sh -c "$K get runtimeclass fake >/dev/null 2>&1" || true
assert_eq "the fake RuntimeClass runs its handler on the nodes that declare it" \
  'fake {"runtime.stratum.ciq.com/fake":"true"}' "$(rc_fake)"

pod rh-fake fake
pod rh-plain
wait_for "a pod under the fake RuntimeClass to run" 180 running rh-fake || fail "rh-fake: $($K describe pod rh-fake | tail -15)"
wait_for "a pod with no RuntimeClass to run" 180 running rh-plain || fail "rh-plain: $($K describe pod rh-plain | tail -15)"
if ran_through_fake rh-fake; then pass "the fake handler's binary ran rh-fake's container"; else fail "$LOG has no call for rh-fake's container: $(tail -5 "$LOG" 2>/dev/null)"; fi
if ran_through_fake rh-plain; then fail "a pod with no RuntimeClass ran through the fake handler"; else pass "a pod with no RuntimeClass ran under the default runc"; fi
assert_contains "the RuntimeClass put its node selector on the pod" "runtime.stratum.ciq.com/fake" \
  "$($K get pod rh-fake -o jsonpath='{.spec.nodeSelector}')"

# --- stratum runtime restart ----------------------------------------------------
before=$(container_id rh-fake)
out=$("$STRATUM" runtime restart 2>&1) || fail "stratum runtime restart failed: $out"
wait_for "rh-fake to run after containerd restarts" 120 running rh-fake || true
assert_eq "the pod's container outlived containerd's restart" "$before" "$(container_id rh-fake)"
if has_label fake; then pass "the label survives the restart"; else fail "the restart removed the fake label: $(labels)"; fi
if out=$(runtime_check); then pass "stratum runtime check passes after the restart"; else fail "check after restart: $out"; fi

# --- a second handler, day 2 ----------------------------------------------------
config "{fake: $FAKE, fake2: $FAKE}" "[fake]"
out=$("$STRATUM" runtime apply 2>&1) || fail "stratum runtime apply failed: $out"
assert_contains "apply restarted containerd to load the new handler" "containerd restarted to load the runtime handlers" "$out"
assert_contains "the drop-in declares the second handler" "containerd.runtimes.fake2]" "$(cat "$DROPIN")"
wait_for "the node's fake2 handler label" 120 has_label fake2 || fail "the node has no fake2 label: $(labels)"
if out=$(runtime_check); then pass "stratum runtime check passes with two handlers"; else fail "check with two handlers: $out"; fi

# --- a second stratum up --------------------------------------------------------
config "{fake: $FAKE, fake2: $FAKE}" "[fake, fake2]"
stop_cluster
start_cluster
ready
assert_contains "the drop-in survives a second start" "containerd.runtimes.fake2]" "$(cat "$DROPIN" 2>/dev/null)"
both() { has_label fake && has_label fake2; }
wait_for "both handler labels after a second start" 120 both || fail "labels after a second start: $(labels)"
assert_eq "rh-fake kept running through the second start" "$before" "$(container_id rh-fake)"
wait_for "the fake2 RuntimeClass" 180 sh -c "$K get runtimeclass fake2 >/dev/null 2>&1" || fail "no fake2 RuntimeClass"
pod rh-fake2 fake2
wait_for "a pod under the fake2 RuntimeClass to run" 180 running rh-fake2 || fail "rh-fake2: $($K describe pod rh-fake2 | tail -15)"
if ran_through_fake rh-fake2; then pass "the second handler's binary ran rh-fake2's container"; else fail "$LOG has no call for rh-fake2's container"; fi

# --- removing the last handler --------------------------------------------------
$K delete pod rh-fake rh-fake2 --wait=true --timeout=60s >/dev/null 2>&1 || true
config "{}" "[]"
out=$("$STRATUM" runtime apply 2>&1) || fail "stratum runtime apply with no handlers failed: $out"
if [[ -e $DROPIN ]]; then fail "the drop-in is still there with no handlers: $(cat "$DROPIN")"; else pass "removing the last handler removes the drop-in"; fi
none() { ! labels | grep -q 'runtime.stratum.ciq.com/'; }
wait_for "the handler labels to go" 120 none || fail "handler labels left: $(labels)"
if out=$(runtime_check); then pass "stratum runtime check passes with no handlers"; else fail "check with no handlers: $out"; fi

done_testing
