#!/usr/bin/env bash
# Generates the static update-channel index: channels/<name>/index.yaml
# with version, per-arch artifact URLs + sha256, and an EOL flag. No backend:
# it is served from object storage or GitHub Pages.
#
# Run by the release pipeline AFTER artifacts are published; publishing the
# channel is a release GATE, not an afterthought: a channel that falls behind
# serves a stale version indefinitely. The index is cosign-signed when cosign
# is present, closing the update-server-compromise hole.
#
# Usage: tools/gen-channel.sh --channel stable --version vX.Y.Z-stratum.N \
#          --url-base https://.../releases/download [--sums sha256sums.txt]
#          [--eol] [--out channels/]
#
# --sums is the release's published sha256sums.txt. Pass it in the pipeline: a
# channel that advertises a URL without the matching hash is a channel whose
# whole point (a client can tell it got the right bytes) has been thrown away.
set -euo pipefail
cd "$(dirname "$0")/.."

CHANNEL=stable VERSION="" URLBASE="" SUMS="" EOL=false OUT=channels
while [[ $# -gt 0 ]]; do
  case $1 in
    --channel) CHANNEL=$2; shift 2 ;;
    --version) VERSION=$2; shift 2 ;;
    --url-base) URLBASE=$2; shift 2 ;;
    --sums) SUMS=$2; shift 2 ;;
    --eol) EOL=true; shift ;;
    --out) OUT=$2; shift 2 ;;
    *) echo "usage: $0 --channel C --version vX-stratum.N --url-base URL [--sums FILE] [--eol] [--out DIR]" >&2; exit 2 ;;
  esac
done
[[ -n $VERSION && -n $URLBASE ]] || { echo "gen-channel: --version and --url-base are required" >&2; exit 2; }

# Per-minor channel alongside the named one: stable/v1.36 pins a minor.
minor=$(printf '%s' "$VERSION" | sed -E 's/^v([0-9]+\.[0-9]+).*/v\1/')

# The sha256 a client will check the download against. From the release's own
# sha256sums.txt when the pipeline passes one; from dist/ for a local run, so the
# format is exercised end to end without a release existing.
sum_for() {  # $1 = arch
  local name="stratum-linux-$1"
  if [[ -n $SUMS ]]; then
    local s
    s=$(awk -v f="$name" '$2 == f || $2 == "*"f {print $1}' "$SUMS" | head -1)
    [[ -n $s ]] || { echo "gen-channel: $SUMS has no entry for $name" >&2; exit 1; }
    printf '%s' "$s"
  elif [[ -f dist/stratum ]]; then
    shasum -a256 dist/stratum | cut -d' ' -f1
  else
    printf 'unpublished-run-after-artifacts-exist'
  fi
}

emit() {  # $1 = channel dir
  local dir="$OUT/$1"
  mkdir -p "$dir"
  {
    printf '# SKE update channel "%s" — generated by tools/gen-channel.sh; consumed by\n' "$1"
    # shellcheck disable=SC2016  # the backticks are Markdown for the reader, not a substitution
    printf '# `stratum update check` and the autopilot operator.\n'
    printf 'channel: %s\n' "$1"
    printf 'version: %s\n' "$VERSION"
    printf 'eol: %s\n' "$EOL"
    printf 'artifacts:\n'
    for arch in amd64 arm64; do
      printf '  linux-%s:\n    url: %s/%s/stratum-linux-%s\n    sha256: %s\n' \
        "$arch" "$URLBASE" "$VERSION" "$arch" "$(sum_for "$arch")"
    done
  } > "$dir/index.yaml"
  if command -v cosign >/dev/null; then
    cosign sign-blob --yes "$dir/index.yaml" \
      --output-signature "$dir/index.yaml.sig" --output-certificate "$dir/index.yaml.pem"
  else
    echo "gen-channel: cosign not installed — index UNSIGNED (CI signs keylessly)"
  fi
  echo "gen-channel: wrote $dir/index.yaml ($VERSION, eol=$EOL)"
}
emit "$CHANNEL"
emit "$CHANNEL/$minor"
