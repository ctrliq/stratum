#!/usr/bin/env bash
# Renders the embedded Cilium manifest at the PINNED cilium version — the same
# helm-template recipe, with the version taken from the Makefile's
# CILIUM_VERSION (derived from build/images.txt, the pin surface for images,
# so the render check cannot disagree with the stamped binary) and helm run
# in a container (nothing new installed on build hosts).
#
# Only kubeProxyReplacement=true is rendered: kube-proxy is not built, shipped
# or supported, so there is exactly one service dataplane.
#
# l2announcements.enabled=true completes the bare-metal LoadBalancer story we
# already half-ship with enable-lb-ipam: it adds the coordination.k8s.io/leases
# rule the cilium agent needs to elect a per-service announcer. Without it an
# operator who turns on L2 announcements gets an LB-IPAM IP that nothing ARPs
# for. The announcer is inert until a CiliumL2AnnouncementPolicy
# selects services, so enabling it here changes no default behaviour.
#
# nodePort.addresses={0.0.0.0/0,::/0} makes every address on the native
# devices a NodePort frontend, as kube-proxy answers NodePorts on every local
# address. Left empty, Cilium uses only each device's primary address, so the
# kube-vip VIP, a secondary /32 on the holder's interface, did not answer a
# NodePort from any other host.
#
# Every image reference the chart emits is rewritten to __STRATUM_REGISTRY__/<name>
# on the way out. A running cluster pulls from the SKE mirror and nowhere else;
# the sentinel is resolved at render time from the linker-stamped
# addons.ImageRegistry, so the mirror namespace is not written down here either.
#
# Usage:
#   tools/gen-cilium-manifest.sh           regenerate the committed manifest
#   tools/gen-cilium-manifest.sh --check   fail, with a diff, if it is stale
#
# Every image the manifest pulls must also be in build/images.txt, by the same
# tag AND digest, or the airgap payload and the mirror lack it. Renovate bumps
# the cilium and operator lines there; the Envoy image is the chart's own pin,
# which Renovate never sees, so write mode copies it from the render.
set -euo pipefail
cd "$(dirname "$0")/.."

CHECK=
case ${1:-} in
  "") ;;
  --check) CHECK=1 ;;
  *) echo "usage: $0 [--check]" >&2; exit 2 ;;
esac

VER=$(make -s --no-print-directory print-cilium-version)
[[ -n $VER ]] || { echo "gen-cilium-manifest: no cilium version — make print-cilium-version resolved empty (the pin lives in build/images.txt)" >&2; exit 1; }
OUT=internal/addons/manifests/cilium-kpr-true.yaml

{
  printf '# Generated by tools/gen-cilium-manifest.sh — DO NOT EDIT BY HAND.\n'
  printf '# helm template cilium cilium/cilium --version %s (see the script for values)\n' "$VER"
  printf '# __STRATUM_APISERVER_HOST__ and __STRATUM_APISERVER_URLS__ are filled in at apply\n'
  printf '# time from the cluster (internal/addons.FillAPIServer, called by the operator).\n'
  docker run --rm docker.io/alpine/helm:3 template cilium cilium \
    --repo https://helm.cilium.io --version "$VER" --namespace kube-system \
    --set routingMode=tunnel --set tunnelProtocol=vxlan \
    --set kubeProxyReplacement=true \
    --set bpf.masquerade=true \
    --set ipam.mode=kubernetes \
    --set k8sServiceHost=__STRATUM_APISERVER_HOST__ --set k8sServicePort=6443 \
    --set k8s.apiServerURLs=__STRATUM_APISERVER_URLS__ \
    --set hubble.enabled=false \
    --set l2announcements.enabled=true \
    --set 'nodePort.addresses={0.0.0.0/0,::/0}' \
    --set rollOutCiliumPods=true \
    --set operator.rollOutPods=true \
    --set updateStrategy.rollingUpdate.maxUnavailable=1 \
  | sed -E 's|(image: *"?)[^"[:space:]]*/([^/"[:space:]]+:)|\1__STRATUM_REGISTRY__/\2|'
} > "$OUT.tmp"

# What the manifest pulls, as <name>:<tag>@<digest> — the same last-path-component
# naming tools/mirror-images.sh gives the mirror.
WANT=$(grep -oE '__STRATUM_REGISTRY__/[^"[:space:]]+' "$OUT.tmp" | sed 's|^__STRATUM_REGISTRY__/||' | sort -u)

if [[ -n $CHECK ]]; then
  if ! diff -u "$OUT" "$OUT.tmp"; then
    rm -f "$OUT.tmp"
    echo "gen-cilium-manifest: $OUT does not match a fresh render; run tools/gen-cilium-manifest.sh and commit the result" >&2
    exit 1
  fi
  rm -f "$OUT.tmp"
else
  mv "$OUT.tmp" "$OUT"
  ENVOY=$(grep '^cilium-envoy:' <<<"$WANT" || true)
  if [[ -n $ENVOY ]]; then
    sed "s|^quay.io/cilium/cilium-envoy:.*|quay.io/cilium/$ENVOY|" build/images.txt > build/images.txt.tmp
    mv build/images.txt.tmp build/images.txt
  fi
fi

SHIPPED=$(grep -vE '^[[:space:]]*(#|$)' build/images.txt | sed 's|.*/||' | sort -u)
MISSING=$(comm -23 <(printf '%s\n' "$WANT") <(printf '%s\n' "$SHIPPED"))
if [[ -n $MISSING ]]; then
  printf '%s\n' "$MISSING" >&2
  echo "gen-cilium-manifest: $OUT pulls the images above, but build/images.txt does not ship them at that tag and digest; add or fix their lines there" >&2
  exit 1
fi

if [[ -n $CHECK ]]; then
  echo "gen-cilium-manifest: $OUT matches a fresh render (cilium $VER, kpr=true)"
  exit 0
fi
echo "gen-cilium-manifest: wrote $OUT (cilium $VER, kpr=true)"

# The manifest must agree with the pin — catch a stale rendering in CI.
grep -q "__STRATUM_REGISTRY__/cilium:v$VER" "$OUT" || {
  echo "gen-cilium-manifest: rendered manifest does not carry cilium v$VER" >&2; exit 1; }

# …and nothing may have escaped the rewrite. A single surviving quay.io ref is a
# pod that pulls from the internet on an airgapped cluster.
if grep -nE '^\s*-?\s*image: *"?[^"[:space:]]*\.[a-z]{2,}/' "$OUT"; then
  echo "gen-cilium-manifest: the lines above still name an upstream registry" >&2; exit 1
fi
