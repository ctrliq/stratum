func TestCheckFile(t *testing.T) {
	long := "// " + strings.Repeat("x", maxCommentLen)
	cases := []struct {
		name string
		src  string
		want []string
	}{
		{"one line passes", "package p\n\n// P is fine.\nvar P int\n", nil},
		{"trailing comments pass", "package p\n\nvar (\n\tA = 1 // a\n\tB = 2 // b\n)\n", nil},
		{"two lines fail", "package p\n\n// One.\n// Two.\nvar P int\n", []string{"3: comment is 2 lines"}},
		{"block comment lines count", "package p\n\n/* one\ntwo */\nvar P int\n", []string{"3: comment is 2 lines"}},
		{"directives are exempt", "//go:build e2e\n\n// Package p does a thing.\npackage p\n\n// P is fine.\n//\n//go:noinline\nfunc P() {}\n", nil},
		{"gofmt directive layout passes", "package p\n\nimport \"embed\"\n\n// Built by make.\n//\n//go:embed all:dist\nvar dist embed.FS\n", nil},
		{"blank separator does not hide a second line", "package p\n\n// One.\n//\n// Two.\nvar P int\n", []string{"3: comment is 2 lines"}},
		{"directive beside one line passes", "package p\n\n// P is fine.\n//go:noinline\nfunc P() {}\n", nil},
		{"generated header is exempt", "// Code generated by x. DO NOT EDIT.\n\npackage p\n", nil},
		{"long line fails", "package p\n\n" + long + "\nvar P int\n", []string{"3: comment line is 103 characters"}},
		{"section sign fails", "package p\n\n// See §16.\nvar P int\n", []string{`3: spec section reference "§"`}},
		{"tracker fails", "package p\n\n// Fixes KUB-" + "12.\nvar P int\n", []string{`3: tracker reference "KUB-` + `12"`}},
		{"pull request fails", "package p\n\n// From #384.\nvar P int\n", []string{`3: issue or pull request reference "#384"`}},
		{"todo fails", "package p\n\n// TODO: drop.\nvar P int\n", []string{`3: task note "TODO"`}},
		{"task state fails", "package p\n\n// Red until the fix lands.\nvar P int\n", []string{`3: task-state narration "Red until"`, `3: history narration "until the fix"`}},
		{"for now fails", "package p\n\n// Skipped for now.\nvar P int\n", []string{`3: task-state narration "for now"`}},
		{"used to fails", "package p\n\n// A flush used to count as written.\nvar P int\n", []string{`3: history narration "used to"`}},
		{"old version fails", "package p\n\n// The old version's default was wrong.\nvar P int\n", []string{`3: history narration "The old version"`}},
		{"once accepted fails", "package p\n\n// A substring once accepted a bad rule.\nvar P int\n", []string{`3: history narration "once accepted a"`}},
		{"now refuses fails", "package p\n\n// A rebuild now refuses the cluster.\nvar P int\n", []string{`3: history narration "rebuild now refuses"`}},
		{"func Now doc passes", "package p\n\n// Now returns the time in UTC.\nfunc Now() {}\n", nil},
		{"state no longer passes", "package p\n\n// Cleared when the key no longer matches.\nvar P int\n", nil},
		{"we fails", "package p\n\n// Here we read the key.\nvar P int\n", []string{`3: first-person narration "we"`}},
		{"step fails", "package p\n\nfunc P() {\n\t// Step 2: dial.\n}\n", []string{`4: step-by-step narration; extract named functions "// Step 2"`}},
		{"block step fails", "package p\n\nfunc P() {\n\t/* Step 2: dial. */\n}\n", []string{`4: step-by-step narration; extract named functions "/* Step 2"`}},
		{"block step on a later line fails", "package p\n\nfunc P() {\n\t/* Dial.\n\t * Step 3: read. */\n}\n", []string{`5: step-by-step narration; extract named functions "* Step 3"`, "4: comment is 2 lines"}},
		{"strings are not comments", "package p\n\nvar P = \"§1 KUB-" + "1 #2 TODO red until\"\n", nil},
		{"SHA-256 is not a tracker", "package p\n\n// P is a SHA-256 sum.\nvar P int\n", nil},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			got, err := checkFile("p.go", []byte(c.src))
			if err != nil {
				t.Fatal(err)
			}
			if len(got) != len(c.want) {
				t.Fatalf("got %d findings %v, want %v", len(got), got, c.want)
			}
			for i, f := range got {
				line := strings.TrimPrefix(f.pos.String(), "p.go:")
				line = line[:strings.Index(line, ":")] + ": " + f.msg
				if !strings.HasPrefix(line, c.want[i]) {
					t.Errorf("finding %d = %q, want prefix %q", i, line, c.want[i])
				}
			}
		})
	}
}

func TestPublicAPIExportedDocsMayRunSeveralLines(t *testing.T) {
	cases := []struct {
		name, path, src string
		want            []string
	}{
		{"exported func", "pkg/cli/x.go", "package cli\n\n// F does one thing.\n// It also does another.\nfunc F() {}\n", nil},
		{"exported type", "pkg/cli/x.go", "package cli\n\n// T is one thing.\n// And another.\ntype T int\n", nil},
		{"exported var in a group", "pkg/cli/x.go", "package cli\n\nvar (\n\t// V is one.\n\t// And two.\n\tV int\n)\n", nil},
		{"exported struct field", "pkg/cli/x.go", "package cli\n\ntype T struct {\n\t// A is one.\n\t// And two.\n\tA int\n}\n", nil},
		{"exported interface method", "pkg/cli/x.go", "package cli\n\ntype I interface {\n\t// M is one.\n\t// And two.\n\tM()\n}\n", nil},
		{"unexported field", "pkg/cli/x.go", "package cli\n\ntype T struct {\n\t// a one.\n\t// a two.\n\ta int\n}\n", []string{"4: comment is 2 lines"}},
		{"field of unexported type", "pkg/cli/x.go", "package cli\n\ntype t struct {\n\t// A one.\n\t// A two.\n\tA int\n}\n", []string{"4: comment is 2 lines"}},
		{"absolute root", "/r/pkg/cli/x.go", "package cli\n\n// F one.\n// F two.\nfunc F() {}\n", nil},
		{"unexported func", "pkg/cli/x.go", "package cli\n\n// f one.\n// f two.\nfunc f() {}\n", []string{"3: comment is 2 lines"}},
		{"comment in a body", "pkg/cli/x.go", "package cli\n\nfunc F() {\n\t// One.\n\t// Two.\n}\n", []string{"4: comment is 2 lines"}},
		{"test file", "pkg/cli/x_test.go", "package cli\n\n// F one.\n// F two.\nfunc F() {}\n", []string{"3: comment is 2 lines"}},
		{"other package", "internal/x/x.go", "package x\n\n// F one.\n// F two.\nfunc F() {}\n", []string{"3: comment is 2 lines"}},
		{"subpackage", "pkg/cli/sub/x.go", "package sub\n\n// F one.\n// F two.\nfunc F() {}\n", []string{"3: comment is 2 lines"}},
		{"banned phrase still fails", "pkg/cli/x.go", "package cli\n\n// F one.\n// See §2.\nfunc F() {}\n", []string{`4: spec section reference "§"`}},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			got, err := checkFile(c.path, []byte(c.src))
			if err != nil {
				t.Fatal(err)
			}
			if len(got) != len(c.want) {
				t.Fatalf("got %d findings %v, want %d %v", len(got), got, len(c.want), c.want)
			}
			for i, w := range c.want {
				if s := fmt.Sprintf("%d: %s", got[i].pos.Line, got[i].msg); !strings.HasPrefix(s, w) {
					t.Errorf("finding %d = %q, want prefix %q", i, s, w)
				}
			}
		})
	}
}

