package addons

import (
	"fmt"
	"slices"
	"strings"

	"github.com/ctrliq/stratum/internal/k8sutil"
)

// The stack the cluster's RuntimeClasses are staged in, only while spec.runtimeClasses names any.
const RuntimeClassStack = "runtime-classes"

// RuntimeClassHeader tells a file Stratum staged from one an administrator dropped there.
const RuntimeClassHeader = "# Generated by stratum from spec.runtimeClasses. Do not edit: every control-plane start rewrites it.\n"

// Renders one RuntimeClass per handler; none is a default, so a pod must name its RuntimeClass.
func RenderRuntimeClasses(names []string) []byte {
	if len(names) == 0 {
		return nil
	}
	docs := make([]string, 0, len(names))
	for _, n := range slices.Sorted(slices.Values(names)) {
		docs = append(docs, fmt.Sprintf(`apiVersion: node.k8s.io/v1
kind: RuntimeClass
metadata:
  name: "%[1]s"
handler: "%[1]s"
scheduling:
  nodeSelector:
    %[2]s%[1]s: "true"
`, n, k8sutil.RuntimeHandlerLabelPrefix))
	}
	return []byte(RuntimeClassHeader + strings.Join(docs, "---\n"))
}
