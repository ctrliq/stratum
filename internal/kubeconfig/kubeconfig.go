// Package kubeconfig writes the control-plane kubeconfigs in Go using
// client-go's clientcmd/api. Certs are embedded from version.PKIDir. Idempotent.
package kubeconfig

import (
	"fmt"
	"net"
	"os"
	"path/filepath"
	"strconv"

	"k8s.io/client-go/tools/clientcmd"
	clientcmdapi "k8s.io/client-go/tools/clientcmd/api"

	"github.com/ctrliq/stratum/internal/atomicfile"
	"github.com/ctrliq/stratum/internal/pki"
	"github.com/ctrliq/stratum/internal/version"
)

// Entry describes one kubeconfig to write.
type Entry struct {
	File     string // basename under version.KubeconfigDir, or an absolute path
	User     string // context user name
	CertName string // PKI basename for the client cert/key (e.g. "admin")
}

// Write generates a single kubeconfig (cluster=oss) pointing at server, with the
// CA + client cert/key embedded from the PKI dir. The embedded CA comes from
// pki's one trust reader: the bundle (ca-bundle.crt) so a kubeconfig keeps
// working across a CA rotation (old‖new), falling back to ca.crt on clusters
// predating the bundle files.
func Write(e Entry, server string) error {
	ca, _, err := pki.ReadRootTrust()
	if err != nil {
		return err
	}
	crt, err := os.ReadFile(filepath.Join(version.PKIDir, e.CertName+".crt"))
	if err != nil {
		return fmt.Errorf("read %s.crt: %w", e.CertName, err)
	}
	key, err := os.ReadFile(filepath.Join(version.PKIDir, e.CertName+".key"))
	if err != nil {
		return fmt.Errorf("read %s.key: %w", e.CertName, err)
	}
	cfg := clientcmdapi.NewConfig()
	cfg.Clusters[version.ClusterName] = &clientcmdapi.Cluster{
		Server:                   server,
		CertificateAuthorityData: ca,
	}
	cfg.AuthInfos[e.User] = &clientcmdapi.AuthInfo{
		ClientCertificateData: crt,
		ClientKeyData:         key,
	}
	cfg.Contexts["default"] = &clientcmdapi.Context{
		Cluster:  version.ClusterName,
		AuthInfo: e.User,
	}
	cfg.CurrentContext = "default"

	out := e.File
	if !filepath.IsAbs(out) {
		out = filepath.Join(version.KubeconfigDir, out)
	}
	if err := os.MkdirAll(version.KubeconfigDir, 0o755); err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(out), 0o700); err != nil {
		return err
	}
	// Render with clientcmd.Write and write atomically: clientcmd.WriteToFile
	// truncates the file in place, and a kubeconfig cut in half stops the
	// component that authenticates with it (on a worker, the kubelet) from
	// starting at all.
	b, err := clientcmd.Write(*cfg)
	if err != nil {
		return err
	}
	return atomicfile.WriteFile(out, b, 0o600)
}

// CurrentServer returns the cluster server URL recorded in an existing
// kubeconfig (e.g. version.AdminConf). Used by cert rotation to rewrite the
// kubeconfigs while preserving the current endpoint — critical after
// `ha-repoint`, which points them at the per-node LB (127.0.0.1:7445) rather
// than the local apiserver (127.0.0.1:6443).
func CurrentServer(file string) (string, error) {
	cfg, err := clientcmd.LoadFromFile(file)
	if err != nil {
		return "", err
	}
	if c, ok := cfg.Clusters[version.ClusterName]; ok && c.Server != "" {
		return c.Server, nil
	}
	for _, c := range cfg.Clusters { // fall back to any cluster entry
		if c.Server != "" {
			return c.Server, nil
		}
	}
	return "", fmt.Errorf("kubeconfig %s has no cluster server URL", file)
}

// ReadWithClusterCA reads an existing kubeconfig and returns its bytes with every cluster's
// embedded certificate-authority-data rewritten to ca, preserving everything else
// (server, auth, contexts). A CA-rotation helper for kubeconfigs that embed the CA
// and are NOT regenerated by GenerateAll — notably a worker's kubelet.kubeconfig +
// bootstrap-kubeconfig, whose embedded CA is how the kubelet verifies the
// apiserver's serving cert.
//
// It returns bytes rather than writing them so a caller updating several files
// together can stage them all before committing any. clientcmd.WriteToFile is a
// plain os.WriteFile with no temp file, and a truncated kubelet.kubeconfig stops
// the kubelet from starting at all — on a worker, that is a node nobody is logged
// in to.
func ReadWithClusterCA(file string, ca []byte) ([]byte, error) {
	cfg, err := clientcmd.LoadFromFile(file)
	if err != nil {
		return nil, err
	}
	for _, c := range cfg.Clusters {
		c.CertificateAuthorityData = ca
		c.CertificateAuthority = "" // prefer the embedded data over any stale file ref
	}
	return clientcmd.Write(*cfg)
}

// kubeconfigLeaves selects the pki leaves that authenticate to the apiserver
// with a client certificate and so get a kubeconfig of their own. pki's leaf
// specs own the client-certificate file names and the context user names (the
// leaves' CNs); this list only selects which leaves map to a kubeconfig.
var kubeconfigLeaves = []string{"admin", "controller-manager", "kubelet"}

// entryForLeaf returns the kubeconfig Entry for a pki leaf: the file
// <leaf>.kubeconfig, the leaf's CN as the context user, and the leaf's
// certificate/key pair as the client credential.
func entryForLeaf(leaf, host string) (Entry, bool) {
	for _, s := range pki.LeafSpecs(host, "", nil) {
		if s.Name != leaf {
			continue
		}
		return Entry{File: s.Name + ".kubeconfig", User: s.CN, CertName: s.Name}, true
	}
	return Entry{}, false
}

// NodeServerURL is the apiserver endpoint every kubeconfig on a node targets,
// from the node-state record's endpoint facts: the endpoint the record
// carries (NodeState.Server — bring-up, the HA join, and ha-repoint all
// record the endpoint they chose or moved the clients to), else the VIP when
// one is configured (one address for in-cluster and external clients), else
// the local apiserver. Bring-up's serverURL and the join's recorded endpoint
// derive through it, so every writer records and writes one endpoint.
func NodeServerURL(server, vip string) string {
	if server != "" {
		return server
	}
	if vip != "" {
		return "https://" + net.JoinHostPort(vip, strconv.Itoa(version.APIServerPort))
	}
	return fmt.Sprintf("https://127.0.0.1:%d", version.APIServerPort)
}

// GenerateAll writes the control-plane kubeconfigs targeting server and copies
// admin → /etc/kubernetes/admin.conf. The caller passes the node-state
// record's endpoint facts: bring-up and the HA join pass the recorded
// endpoint (NodeState.Server, by NodeServerURL's rule) and the record's
// kube-vip marker; renewal and the CA rotations keep the endpoint the node's
// admin.conf already holds (CurrentServer). With vip set it also writes
// kube-vip.kubeconfig, always against the local apiserver rather than server:
// kube-vip's own election client must not depend on the VIP it manages.
// version.SuperAdminConf is among them once the super-admin leaf exists: a
// control plane an earlier release started has none until its next
// `stratum up`, yet CA rotation's trust-new regenerates its kubeconfigs
// without issuing leaves, and k8sutil.InternalAdminConf falls back to
// admin.conf meanwhile.
//
// kube-vip's kubeconfig lives here rather than beside each caller because it
// embeds the CA bundle and client cert like the others, so anything that
// reissues leaves or moves trust must rewrite it too. When only `up` and the HA
// join wrote it, CA rotation's sign-new left it trusting the old CA alone: the
// apiservers started serving new-CA certs, kube-vip could not renew its Lease,
// and no node held the VIP.
func GenerateAll(host, server string, vip bool) error {
	var entries []Entry
	for _, leaf := range kubeconfigLeaves {
		e, ok := entryForLeaf(leaf, host)
		if !ok {
			return fmt.Errorf("pki has no %s leaf: the %s kubeconfig has no client certificate to embed", leaf, leaf)
		}
		entries = append(entries, e)
	}
	if leafIssued("super-admin") {
		entries = append(entries, Entry{File: version.SuperAdminConf(), User: "super-admin", CertName: "super-admin"})
	}
	for _, e := range entries {
		if err := Write(e, server); err != nil {
			return fmt.Errorf("kubeconfig %s: %w", e.File, err)
		}
	}
	if err := WriteScheduler(server); err != nil {
		return err
	}
	if vip {
		if err := WriteKubeVip(); err != nil {
			return err
		}
	}
	// admin.conf for kubectl default — also the operator's --kubeconfig, so the
	// copy goes through the shared atomic writer like every write above: a
	// truncated one leaves a control plane whose operator cannot authenticate.
	if err := os.MkdirAll(version.K8sConfDir, 0o755); err != nil {
		return err
	}
	src := filepath.Join(version.KubeconfigDir, "admin.kubeconfig")
	data, err := os.ReadFile(src)
	if err != nil {
		return err
	}
	return atomicfile.WriteFile(version.AdminConf, data, 0o600)
}

// leafIssued reports whether the leaf's certificate and key are both in
// version.PKIDir.
func leafIssued(name string) bool {
	for _, ext := range []string{".crt", ".key"} {
		if _, err := os.Stat(filepath.Join(version.PKIDir, name+ext)); err != nil {
			return false
		}
	}
	return true
}

// legacyKubeVipKubeconfig is the path older kube-vip manifests name; a rollback needs it.
func legacyKubeVipKubeconfig() string {
	return filepath.Join(version.KubeconfigDir, "kube-vip.kubeconfig")
}

// WriteKubeVip writes kube-vip's kubeconfig, against the local apiserver, to both paths.
func WriteKubeVip() error {
	server := fmt.Sprintf("https://127.0.0.1:%d", version.APIServerPort)
	for _, f := range []string{version.KubeVipKubeconfig(), legacyKubeVipKubeconfig()} {
		if err := Write(Entry{File: f, User: "system:kube-vip", CertName: "kube-vip"}, server); err != nil {
			return fmt.Errorf("kubeconfig %s: %w", f, err)
		}
	}
	return nil
}

// legacySchedulerKubeconfig is the path older kube-scheduler manifests name;
// a rollback needs it.
func legacySchedulerKubeconfig() string {
	return filepath.Join(version.KubeconfigDir, "scheduler.kubeconfig")
}

// WriteScheduler writes kube-scheduler's kubeconfig, against server, to both
// paths.
func WriteScheduler(server string) error {
	for _, f := range []string{version.SchedulerKubeconfig(), legacySchedulerKubeconfig()} {
		if err := Write(Entry{File: f, User: "system:kube-scheduler", CertName: "scheduler"}, server); err != nil {
			return fmt.Errorf("kubeconfig %s: %w", f, err)
		}
	}
	return nil
}

// RefreshScheduler writes kube-scheduler's kubeconfig to both paths against
// the server the one at the legacy path names.
func RefreshScheduler() error {
	server, err := CurrentServer(legacySchedulerKubeconfig())
	if err != nil {
		return fmt.Errorf("read kube-scheduler's server: %w", err)
	}
	return WriteScheduler(server)
}

// SetServer rewrites the server URL of every cluster in a kubeconfig,
// preserving everything else — the HA repoint primitive. The rewrite is
// atomic and keeps the file at 0600: it rewrites the kubeconfig the kubelet
// authenticates with, and a truncated one stops a worker nobody is logged in to.
func SetServer(file, server string) error {
	cfg, err := clientcmd.LoadFromFile(file)
	if err != nil {
		return err
	}
	for _, c := range cfg.Clusters {
		c.Server = server
	}
	b, err := clientcmd.Write(*cfg)
	if err != nil {
		return err
	}
	return atomicfile.WriteFile(file, b, 0o600)
}
